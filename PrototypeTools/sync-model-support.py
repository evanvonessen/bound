#!/usr/bin/env python3
"""Keep the standalone model harness on the app's actual shared declarations.

The owning sources also contain UIKit views. Extract only platform-neutral
declarations so the macOS test package need not mock policy or preference keys.
Run through PrototypeTools/qa-python; --check is read-only.
"""
import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / "PrototypeTests/Sources/Models"
SOURCES = [
    ("BoundAccountSocial.swift", "BoundSocialSupport.swift",
     "struct BoundSocialResponse: Decodable, Sendable {",
     "@MainActor\nfinal class BoundAccountProfile: ObservableObject {"),
    ("BoundConfigurationExport.swift", "BoundDeveloperFeatures.swift",
     "enum BoundDeveloperFeatures {", "struct BoundConfigurationDocument {"),
]


def generated_source(filename: str, start: str, end: str) -> str:
    source = (ROOT / "Delta/Bound" / filename).read_text()
    if source.count(start) != 1 or source.count(end) != 1:
        raise ValueError(f"{filename} model boundaries changed; review the extraction")
    declarations = source[source.index(start):source.index(end)].rstrip() + "\n"
    return (
        "// Generated by PrototypeTools/sync-model-support.py; do not edit.\n"
        f"// Exact platform-neutral declarations from Delta/Bound/{filename}.\n"
        "import Foundation\n\n" + declarations
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for filename, output_name, start, end in SOURCES:
        output = MODELS / output_name
        expected = generated_source(filename, start, end)
        if args.check:
            if not output.is_file() or output.read_text() != expected:
                raise SystemExit(f"{output_name} differs; run this tool without --check")
        else:
            output.write_text(expected)
    print("Model support matches the production declarations")


if __name__ == "__main__":
    main()
